"""
Export india_states_projected.json as compact SVG path strings for the landing
page map (apps/web/src/pages/indiaMap.ts). Same projection as the 3D scene, so
lon/lat anchors from scene/india.ts land on the right state.

    python export_svg_paths.py  # writes ../../apps/web/src/pages/indiaMap.ts
"""
import json
import os

from simplify_geojson import rdp

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "apps", "web", "src", "pages", "indiaMap.ts")
K = 100       # svg px per projected unit
PAD = 24
EPS = 0.02    # projected units; ~0.07deg, plenty for a ~900px map

with open(os.path.join(HERE, "india_states_projected.json"), encoding="utf-8") as f:
    data = json.load(f)

pts = [p for s in data["states"] for r in s["rings"] for p in r]
min_x, max_x = min(p[0] for p in pts), max(p[0] for p in pts)
min_y, max_y = min(p[1] for p in pts), max(p[1] for p in pts)
W, H = round((max_x - min_x) * K + PAD * 2), round((max_y - min_y) * K + PAD * 2)

def to_svg(x, y):
    return (x - min_x) * K + PAD, (max_y - y) * K + PAD

def svg_pts(line):
    pts = [f"{x:.0f},{y:.0f}" for x, y in (to_svg(x, y) for x, y in line)]
    return [q for i, q in enumerate(pts) if i == 0 or q != pts[i - 1]]  # rounding can collapse neighbours

def inside(rings, x, y):
    for r, (x0, y0, x1, y1) in rings:
        if not (x0 <= x <= x1 and y0 <= y <= y1):
            continue
        c = False
        for (xi, yi), (xj, yj) in zip(r, r[-1:] + r[:-1]):
            if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
                c = not c
        if c:
            return True
    return False

def outline(rings):
    """The state's own border. The source rings are overlapping district polygons, so an edge
    is on the border only if one side of it is inside the state and the other side isn't.
    Border edges are chained into polylines and only then simplified."""
    rings = [[tuple(p) for p in r] for r in rings if len(r) >= 3]
    boxed = [(r, (min(p[0] for p in r), min(p[1] for p in r), max(p[0] for p in r), max(p[1] for p in r))) for r in rings]
    eps = 1e-4
    edges = set()
    for r in rings:
        for a, b in zip(r, r[1:] + r[:1]):
            if a == b:
                continue
            k = (a, b) if a < b else (b, a)
            if k in edges:
                continue
            mx, my = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
            dx, dy = b[0] - a[0], b[1] - a[1]
            n = (dx * dx + dy * dy) ** 0.5
            nx, ny = -dy / n * eps, dx / n * eps
            if inside(boxed, mx + nx, my + ny) != inside(boxed, mx - nx, my - ny):
                edges.add(k)
    adj = {}
    for a, b in edges:
        adj.setdefault(a, []).append(b)
        adj.setdefault(b, []).append(a)
    out = []
    for start in list(adj):
        while adj.get(start):
            line, cur = [start], start
            while adj.get(cur):
                nxt = adj[cur].pop()
                adj[nxt].remove(cur)
                line.append(nxt)
                cur = nxt
            pts = svg_pts(rdp(line, EPS))
            if len(pts) >= 2:
                out.append("M" + "L".join(pts))
    return "".join(out)

states = []
for s in data["states"]:
    rings = []
    for ring in s["rings"]:
        pts = svg_pts(rdp(ring, EPS))
        if pts and pts[0] == pts[-1]:
            pts.pop()
        if len(pts) >= 3:
            rings.append(pts)
    if rings:
        states.append((s["name"], "".join("M" + "L".join(r) + "Z" for r in rings), outline(s["rings"])))

p = data["projection"]
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/blender-india/export_svg_paths.py — do not edit by hand.\n")
    f.write(f"export const MAP_W = {W};\nexport const MAP_H = {H};\n\n")
    f.write("/** Map px <-> projected units (scene/india.ts projectLonLat): px = (x - minX) * k + pad, py = (maxY - y) * k + pad. */\n")
    f.write(f"export const PROJ = {{ minX: {min_x:.5f}, maxY: {max_y:.5f}, k: {K}, pad: {PAD} }};\n\n")
    f.write("/** lon/lat -> map px, same projection as scene/india.ts. */\n")
    f.write("export const toMap = (lon: number, lat: number): [number, number] => [\n")
    f.write(f"  ((lon - {p['lon0']}) * {p['scale']} - PROJ.minX) * PROJ.k + PROJ.pad,\n")
    f.write(f"  (PROJ.maxY - (lat - {p['lat0']}) * {p['scale']}) * PROJ.k + PROJ.pad,\n];\n\n")
    f.write("/** [name, filled district rings, the state's own outline] */\n")
    f.write("export const STATES: Array<[name: string, d: string, outline: string]> = [\n")
    for name, d, o in states:
        f.write(f"  [{json.dumps(name)}, '{d}', '{o}'],\n")
    f.write("];\n")

print(f"{len(states)} states, {W}x{H}, {os.path.getsize(OUT) // 1024} KB -> {OUT}")
